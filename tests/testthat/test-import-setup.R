test_that("raw files with metadata before headers can be manually skipped", {
  path <- tempfile(fileext = ".csv")
  writeLines(c(
    "Report generated by CGM device",
    "Patient,Example",
    "Timestamp,Sensor Glucose (mg/dL),Notes",
    "2026-05-05 08:00:00,100,",
    "2026-05-05 08:05:00,105,"
  ), path)

  probe <- probe_cgm_file_import(path, "raw.csv")
  out <- read_cgm_file(path, "raw.csv", header_row = 3L, first_data_row = 4L)

  expect_equal(probe$suggested_header_row, 3L)
  expect_equal(probe$suggested_first_data_row, 4L)
  expect_true("Timestamp" %in% names(out))
  expect_true("Sensor Glucose (mg/dL)" %in% names(out))
  expect_equal(nrow(out), 2L)
})

