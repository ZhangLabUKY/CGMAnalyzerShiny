test_that("Dexcom-like raw export detects the reading header row", {
  path <- tempfile(fileext = ".csv")
  writeLines(c(
    "Index,Timestamp (YYYY-MM-DDThh:mm:ss),Event Type,Event Subtype,Patient Info,Device Info,Source Device ID,Glucose Value (mg/dL)",
    "1,,FirstName,,John,,,",
    "2,,LastName,,Doe,,,",
    "3,,PatientIdentifier,,08124521,,,",
    "4,,Device,,,Dexcom G7,iOS G7,",
    "5,2024-01-12T00:00:00,EGV,,,,iOS G7,341",
    "6,2024-01-12T00:05:00,EGV,,,,iOS G7,321"
  ), path)

  probe <- probe_cgm_file_import(path, "dexcom.csv")

  expect_equal(probe$profile, "Dexcom")
  expect_equal(probe$suggested_header_row, 1L)
  expect_equal(probe$suggested_first_data_row, 6L)
  expect_equal(probe$detection_status, "Ready")
})

