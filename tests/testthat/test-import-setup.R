test_that("multiple uploaded files support per-file header rows", {
  path_a <- tempfile(fileext = ".csv")
  path_b <- tempfile(fileext = ".csv")
  writeLines(c("time,glucose", "2026-05-05 08:00:00,100"), path_a)
  writeLines(c("metadata", "time,glucose", "2026-05-05 08:00:00,120"), path_b)

  combined <- combine_uploaded_files(
    c(path_a, path_b),
    c("A.csv", "B.csv"),
    header_rows = c(1L, 2L),
    first_data_rows = c(2L, 3L)
  )

  expect_equal(nrow(combined), 2L)
  expect_equal(combined$.source_id, c("A", "B"))
  expect_equal(combined$glucose, c("100", "120"))
})

