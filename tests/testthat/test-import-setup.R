test_that("incompatible resolved schemas produce a clear import message", {
  path_a <- tempfile(fileext = ".csv")
  path_b <- tempfile(fileext = ".csv")
  writeLines(c("time,glucose", "2026-05-05 08:00:00,100"), path_a)
  writeLines(c("timestamp,sensor_glucose,extra", "2026-05-05 08:00:00,120,x"), path_b)

  expect_error(
    combine_uploaded_files(c(path_a, path_b), c("A.csv", "B.csv")),
    "different resolved column names"
  )
})

